#!/usr/bin/env node
/**
 * P03 D7.1 — generate the Tailwind preset from brand/tokens.json.
 *
 * The point of generating it: a Tailwind config maintained by hand is a second copy of the design system,
 * and the second copy is always the one that goes stale (P02 found exactly this inside its own token
 * generator). `bg-bg-base` and `var(--pgm-bg-base)` must be the same value by construction.
 *
 *   node tools/build-tailwind-preset.mjs            # writes web/tailwind.preset.cjs
 *   node tools/build-tailwind-preset.mjs --check    # exit 1 if stale
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(new URL('..', import.meta.url).pathname);
const TOKENS = path.join(ROOT, 'brand/tokens.json');
const OUT = path.join(ROOT, 'web/tailwind.preset.cjs');
const t = JSON.parse(fs.readFileSync(TOKENS, 'utf8'));

const q = (s) => JSON.stringify(String(s));
const num = (v) => (typeof v === 'number' ? String(v) : Number.isNaN(parseFloat(v)) ? q(v) : parseFloat(v));

/* Colours are cross-checked against brand/tokens.css so this preset can never ship a hex that the
   stylesheet disagrees with. tokens.css defines each name once per theme block; we index by name and
   verify both the light and dark values occur, which catches the realistic failure (someone edits one
   file and forgets the other). */
const cssText = fs.readFileSync(path.join(ROOT, 'brand/tokens.css'), 'utf8');
const cssVals = new Map();   // name -> every value assigned to it in the stylesheet
for (const m of cssText.matchAll(/--pgm-([a-z0-9-]+)\s*:\s*([^;]+);/g)) {
  const list = cssVals.get(m[1]) || [];
  list.push(m[2].trim().toLowerCase());
  cssVals.set(m[1], list);
}
function assertInCss(key, value, where) {
  const name = key.replace(/\./g, '-');
  const vals = cssVals.get(name);
  if (!vals) throw new Error(`REFUSING: --pgm-${name} is not in brand/tokens.css. Regenerate it first: node tools/build-tokens.mjs (needed by ${where})`);
  if (!vals.includes(String(value).toLowerCase())) {
    throw new Error(`REFUSING: tokens.json ${key}=${value} but tokens.css defines --pgm-${name} as ${vals.join(' / ')}. The two copies disagree — fix tokens.json, then rebuild.`);
  }
}
const colors = {};
for (const [k, v] of Object.entries(t.semantic.light)) { assertInCss(k, v, 'tailwind:light'); colors[k] = v; }
for (const [k, v] of Object.entries(t.semantic.dark)) { assertInCss(k, v, 'tailwind:dark'); colors[`dark-${k}`] = v; }
for (const [k, v] of t.chart.dark.entries()) { assertInCss(`chart.${k + 1}`, v, 'tailwind:chart'); colors[`chart-dark-${k + 1}`] = v; }
for (const [k, v] of t.chart.light.entries()) { assertInCss(`chart.${k + 1}`, v, 'tailwind:chart'); colors[`chart-light-${k + 1}`] = v; }

const lines = [];
lines.push(`/* GENERATED by tools/build-tailwind-preset.mjs from brand/tokens.json. Do not edit by hand.
   A hand-maintained Tailwind config is a second copy of the design system, and the second copy is the
   one that goes stale. Regenerate both (build-tokens.mjs, then this) after any tokens.json change. */
module.exports = {
  theme: {
    // extend, never replace: a colour added by hand to tailwind.config instead of tokens.json is the
    // failure mode tools/p03-gate-check.py calls "redefined, not consumed".
    extend: {`);

const colourEntries = Object.entries(colors)
  .map(([k, v]) => `        ${q(k.replace(/\./g, '-'))}: ${q(v)},`);
lines.push(`      colors: {\n${colourEntries.join('\n')}\n      },`);

const spacing = Object.fromEntries(t.spacing.scale.map((s) => [s.name, `${s.px}px`]));
for (const o of t.spacing.allowed_offgrid) spacing[`off-${o.px}`] = `${o.px}px`;
lines.push(`      spacing: ${JSON.stringify(spacing)},`);

lines.push(`      borderWidth: ${JSON.stringify(Object.fromEntries(t.border.widths.map((b) => [b.name, `${b.px}px`])))},`);
const shadow = {};
for (const l of t.elevation.levels) shadow[l.name] = l.shadow;
lines.push(`      boxShadow: ${JSON.stringify(shadow)},`);
lines.push(`      borderRadius: ${JSON.stringify({
  base: t.radius.base, chip: t.radius.chip,
  ...Object.fromEntries(['xs', 'sm', 'md', 'xl'].map((k) => [k, `calc(${t.radius.base} ${t.radius[k]})`])),
  '2xl': t.radius['2xl'], '3xl': t.radius['3xl'],
})},`);

const fsz = {};
for (const [mode, px] of Object.entries(t.density.font_size_px)) fsz[mode] = `${px}px`;
for (const s of t.typography.scale) fsz[s.name] = [`${s.size}px`, `${Math.round(s.size * s.line)}px`];
lines.push(`      fontSize: ${JSON.stringify(fsz)},`);

const screens = {};
for (const b of t.breakpoints.values.filter((x) => x.min)) screens[b.name] = `${b.min}px`;
screens['below-sm'] = { max: '639px' };
lines.push(`      screens: ${JSON.stringify(screens)},`);

const dur = {};
for (const [k, v] of Object.entries(t.motion.duration_ms)) if (k !== 'forbidden') dur[k] = `${v.min}ms`;
dur.ceiling = `${t.motion.ui_ceiling_ms}ms`;
lines.push(`      transitionDuration: ${JSON.stringify(dur)},`);
const ease = {};
for (const [k, v] of Object.entries(t.motion.easing)) if (k.startsWith('ease-')) ease[k.slice(5)] = v;
lines.push(`      transitionTimingFunction: ${JSON.stringify(ease)},`);
const z = {};
for (const [k, v] of Object.entries(t.layers)) if (k !== 'note') z[k] = String(v);
lines.push(`      zIndex: ${JSON.stringify(z)},`);
lines.push(`      fontFamily: ${JSON.stringify({
  display: [t.typography.display, 'Inter', 'system-ui', 'sans-serif'],
  body: [t.typography.body, 'Inter', 'system-ui', 'sans-serif'],
  mono: [t.typography.mono, 'ui-monospace', 'monospace'],
})},`);
lines.push(`      lineHeight: ${JSON.stringify(Object.fromEntries(t.typography.scale.map((s) => [s.name, String(s.line)])))},`);
lines.push(`      minWidth: { touch: '${t.density.constants.min_touch_target}px' },
      minHeight: { touch: '${t.density.constants.min_touch_target}px' },`);
lines.push(`    },
  },
  plugins: [],
};`);

const body = lines.join('\n') + '\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.error('web/tailwind.preset.cjs is stale — run: node tools/build-tailwind-preset.mjs'); process.exit(1); }
  console.log('web/tailwind.preset.cjs is up to date with brand/tokens.json');
  process.exit(0);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
const require_ = (await import('node:module')).createRequire(import.meta.url);
try {
  const m = require_(OUT);
  const keys = Object.keys(m.theme.extend);
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${keys.length} theme groups: ${keys.join(', ')}`);
  console.log(`  colours ${Object.keys(m.theme.extend.colors).length} · spacing ${Object.keys(m.theme.extend.spacing).length} · screens ${Object.keys(m.theme.extend.screens).length} · zIndex ${Object.keys(m.theme.extend.zIndex).length}`);
} catch (e) {
  fs.unlinkSync(OUT);
  throw new Error(`generated preset does not load — writing it would break every build downstream: ${e.message}`);
}
